class IncidentModel {
  final String id;
  final String title;
  final String date;
  final String time;
  final String trainerName;
  final String location;
  final String status;
  final String priority;

  IncidentModel({
    required this.id,
    required this.title,
    required this.date,
    required this.time,
    required this.trainerName,
    required this.location,
    required this.status,
    required this.priority,
  });
}
